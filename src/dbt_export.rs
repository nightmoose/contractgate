//! Generate dbt tests from a DataContractGate contract (RFC-119).
//!
//! `schema.yml` carries the three generic tests dbt ships without
//! `dbt_utils` / `dbt_expectations`: `not_null`, `unique`, and
//! `accepted_values`. Everything else `batch_rules` compiles — patterns,
//! formats, ranges, lengths, freshness, and cross-field rules — becomes a
//! singular SQL test file, since there is no portable generic test for
//! them without an extra package dependency.
//!
//! `relationships` tests are not generated: the contract format has no
//! foreign-key concept (RFC-119, "Not in v1").

use crate::batch_rules::{self, RuleCategory};
use crate::contract::{Contract, FieldDefinition, FieldType};
use crate::sql_dialect::SqlDialect;

#[derive(Debug)]
pub struct GeneratedSqlTest {
    pub filename: String,
    pub sql: String,
}

#[derive(Debug)]
pub struct DbtTestsExport {
    pub schema_yml: String,
    pub singular_tests: Vec<GeneratedSqlTest>,
    /// Fields/rules that could not be translated to a dbt test, with why —
    /// surfaced to the caller instead of silently dropped.
    pub skipped: Vec<batch_rules::SkippedRule>,
}

/// `dialect` only affects the singular SQL tests (pattern/format regex
/// syntax, range/length comparisons are dialect-free). `schema.yml`'s
/// generic tests are dbt-native and dialect-independent; dbt's adapter
/// translates them at `dbt test` time.
pub fn generate_dbt_tests(
    contract: &Contract,
    model_name: &str,
    dialect: SqlDialect,
) -> DbtTestsExport {
    let table_ref = format!("{{{{ ref('{model_name}') }}}}");
    let compiled = batch_rules::compile(contract, dialect, &table_ref);

    let schema_yml = render_schema_yml(contract, model_name);

    let singular_tests = compiled
        .predicates
        .iter()
        .filter(|p| {
            // These three are already expressed as schema.yml generic
            // tests above; a singular test would just duplicate them.
            !matches!(
                p.category,
                RuleCategory::Required | RuleCategory::Enum | RuleCategory::Unique
            )
        })
        .map(|p| GeneratedSqlTest {
            filename: format!("{}.sql", p.rule_id.replace([':', '[', ']', '.'], "_")),
            sql: render_singular_test(&table_ref, p),
        })
        .collect();

    DbtTestsExport {
        schema_yml,
        singular_tests,
        skipped: compiled.skipped,
    }
}

fn render_singular_test(table_ref: &str, predicate: &batch_rules::RulePredicate) -> String {
    format!(
        "-- {reason}\n-- Generated by `contractgate export dbt-tests` from rule `{rule_id}`.\n-- A non-empty result fails this test (dbt singular test convention).\nselect *\nfrom {table_ref}\nwhere {predicate}\n",
        reason = predicate.reason,
        rule_id = predicate.rule_id,
        predicate = predicate.predicate_sql,
    )
}

fn render_schema_yml(contract: &Contract, model_name: &str) -> String {
    let mut out = String::new();
    out.push_str("# Generated by `contractgate export dbt-tests`. Do not hand-edit; re-run\n");
    out.push_str("# the export after the contract changes instead.\n");
    out.push_str("version: 2\n\n");
    out.push_str("models:\n");
    out.push_str(&format!("  - name: {model_name}\n"));
    if let Some(description) = &contract.description {
        out.push_str(&format!("    description: {}\n", yaml_scalar(description)));
    }
    out.push_str("    columns:\n");

    let unique_fields = unique_field_names(contract);

    for field in &contract.ontology.entities {
        if matches!(field.field_type, FieldType::Object | FieldType::Array) {
            continue;
        }
        let tests = column_tests(field, unique_fields.contains(&field.name.as_str()));
        out.push_str(&format!("      - name: {}\n", field.name));
        if tests.is_empty() {
            continue;
        }
        out.push_str("        data_tests:\n");
        for t in tests {
            out.push_str(&t);
        }
    }

    if !has_any_object_or_array(contract) {
        return out;
    }
    out.push_str("\n# Skipped (no flat-table equivalent; see RFC-119):\n");
    for field in &contract.ontology.entities {
        if matches!(field.field_type, FieldType::Object | FieldType::Array) {
            out.push_str(&format!(
                "#   - {} ({})\n",
                field.name,
                if field.field_type == FieldType::Object {
                    "object"
                } else {
                    "array"
                }
            ));
        }
    }
    out
}

fn has_any_object_or_array(contract: &Contract) -> bool {
    contract
        .ontology
        .entities
        .iter()
        .any(|f| matches!(f.field_type, FieldType::Object | FieldType::Array))
}

fn unique_field_names(contract: &Contract) -> Vec<&str> {
    contract
        .quality
        .iter()
        .filter(|r| r.rule_type == crate::contract::QualityRuleType::Uniqueness)
        .map(|r| r.field.as_str())
        .collect()
}

fn column_tests(field: &FieldDefinition, is_unique: bool) -> Vec<String> {
    let mut tests = Vec::new();
    if field.required {
        tests.push("          - not_null\n".to_string());
    }
    if is_unique {
        tests.push("          - unique\n".to_string());
    }
    if let Some(values) = &field.allowed_values {
        if let Some(rendered) = render_accepted_values(values) {
            tests.push(format!(
                "          - accepted_values:\n              values: [{rendered}]\n"
            ));
        }
    }
    tests
}

fn render_accepted_values(values: &[serde_json::Value]) -> Option<String> {
    let parts: Option<Vec<String>> = values
        .iter()
        .map(|v| match v {
            serde_json::Value::String(s) => Some(yaml_scalar(s)),
            serde_json::Value::Number(n) => Some(n.to_string()),
            serde_json::Value::Bool(b) => Some(b.to_string()),
            _ => None,
        })
        .collect();
    parts.map(|p| p.join(", "))
}

/// Render a string as a YAML flow scalar, quoting when needed.
fn yaml_scalar(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn contract_yaml() -> &'static str {
        r#"
version: "1.0"
name: orders
description: "Checkout orders"
ontology:
  entities:
    - name: order_id
      type: string
      required: true
      pattern: "^ord_[A-Za-z0-9]{10,32}$"
    - name: amount_usd
      type: number
      required: true
      min: 0
    - name: status
      type: string
      required: true
      enum: ["pending", "paid", "shipped"]
    - name: discount_code
      type: string
      required: false
quality:
  - field: order_id
    type: uniqueness
"#
    }

    #[test]
    fn schema_yml_has_generic_tests_and_no_duplicate_singular() {
        let contract: Contract = serde_yaml::from_str(contract_yaml()).unwrap();
        let out = generate_dbt_tests(&contract, "orders", SqlDialect::Postgres);
        assert!(out.schema_yml.contains("not_null"));
        assert!(out.schema_yml.contains("unique"));
        assert!(out.schema_yml.contains("accepted_values"));
        // pattern and range stay as singular tests; required/unique/enum do not.
        let names: Vec<&str> = out
            .singular_tests
            .iter()
            .map(|t| t.filename.as_str())
            .collect();
        assert!(names.iter().any(|n| n.contains("pattern_order_id")));
        assert!(names.iter().any(|n| n.contains("range_amount_usd")));
        assert!(!names.iter().any(|n| n.contains("required_")));
        assert!(!names.iter().any(|n| n.contains("unique_")));
        assert!(!names.iter().any(|n| n.contains("enum_")));
    }

    #[test]
    fn singular_test_references_ref_macro() {
        let contract: Contract = serde_yaml::from_str(contract_yaml()).unwrap();
        let out = generate_dbt_tests(&contract, "orders", SqlDialect::Postgres);
        let pattern_test = out
            .singular_tests
            .iter()
            .find(|t| t.filename.contains("pattern_order_id"))
            .unwrap();
        assert!(pattern_test.sql.contains("{{ ref('orders') }}"));
    }
}
